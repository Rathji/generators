    function scanPdfs() {
      const out = [];
      if (!window.FS || !window.FS.root) return out;
      (function walk(node, path) {
        if (!node || node.type !== "folder") return;
        for (const c of node.children) {
          const p = path + "/" + c.name;
          if (c.type === "folder") {
            if (window.FS.isInTrash(p)) continue;
            walk(c, p);
          } else if (isPdfNode(c)) {
            out.push({ path: p, name: c.name });
          }
        }
      })(window.FS.root, "");
      out.sort((a, b) => a.path.localeCompare(b.path));
      return out;
    }

    // ---- loading a document ----
    async function load(src) {
      if (inst.disposed) return;
      if (inst.renderTask) { try { inst.renderTask.cancel(); } catch (e) {} inst.renderTask = null; }
      if (inst.doc) { try { inst.doc.destroy(); } catch (e) {} inst.doc = null; }
      ++inst.thumbToken;
      inst.page = 1;
      inst.numPages = 0;
      inst.zoomMode = "fit-width";
      inst.name = src.name || baseName(src.path) || "PDF document";
      inst.path = src.path || null;
      setTitle();
      textLayer.innerHTML = "";
      canvas.width = 2; canvas.height = 2;
      canvas.style.width = ""; canvas.style.height = "";
      wrap.style.width = ""; wrap.style.height = "";
      closeSearch();
      setLoading("Loading PDF engine\u2026", true);
      let pdfjs;
      try { pdfjs = await ensureEngine(); } catch (e) {
        setError("Couldn't load the PDF engine (check your connection) and retry.");
        return;
      }
      if (inst.disposed) return;
      setLoading("Loading document\u2026", true);
      let bytes;
      try {
        if (src.bytes && src.bytes instanceof Uint8Array) bytes = src.bytes;
        else if (src.file && typeof src.file.arrayBuffer === "function") bytes = new Uint8Array(await src.file.arrayBuffer());
        else if (typeof src.content === "string" && /^data:application\/pdf;base64,/i.test(src.content)) bytes = base64ToBytes(src.content.split(",")[1]);
        else if (typeof src.content === "string") bytes = latin1ToBytes(src.content);
        else { setError("That file isn't a readable PDF."); return; }
      } catch (e) {
        setError("That file couldn't be read.");
        return;
      }
      let doc;
      try {
        doc = await pdfjs.getDocument({ data: bytes, disableAutoFetch: true, stopAtErrors: true }).promise;
      } catch (e) {
        setError("This document couldn't be opened - it may be corrupt or not a PDF.");
        return;
      }
      if (inst.disposed) { try { doc.destroy(); } catch (e) {} return; }
      inst.doc = doc;
      inst.numPages = doc.numPages || 1;
      updateStatus();
      empty.hidden = true;
      loading.hidden = true;
      renderCurrent().then(() => renderThumbs());
    }

    function loadByFsPath(path) {
      const res = window.FSPath && window.FSPath.lookup ? window.FSPath.lookup(path) : null;
      if (!res || !res.ok || !isPdfNode(res.node)) return null;
      return load({ path: res.path, name: res.node.name, content: res.node.meta.content });
    }

    function base64ToBytes(b64) {
      const bin = atob(b64);
      const bytes = new Uint8Array(bin.length);
      for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
      return bytes;
    }

    // ---- search ----
    let searchTimer = null;
    function closeSearch() {
      if (searchTimer) { clearTimeout(searchTimer); searchTimer = null; }
      searchRes.hidden = true;
      searchRes.innerHTML = "";
    }
    function runSearch() {
      const q = searchInput.value.trim();
      if (!q || !inst.doc) { closeSearch(); return; }
      setLoading("Searching\u2026", true);
      (async () => {
        const results = [];
        const lq = q.toLowerCase();
        for (let p = 1; p <= inst.numPages && results.length < 60; p++) {
          let page, tc;
          try { page = await inst.doc.getPage(p); tc = await page.getTextContent(); } catch (e) { continue; }
          const full = tc.items.map((i) => i.str).join(" ").replace(/\s+/g, " ").trim();
          const lf = full.toLowerCase();
          let idx = lf.indexOf(lq);
          let count = 0;
          while (idx !== -1) { count++; idx = lf.indexOf(lq, idx + lq.length); }
          if (count) {
            const at = full.toLowerCase().indexOf(lq);
            const snippet = (at > 40 ? "\u2026" : "") + full.slice(Math.max(0, at - 40), at + 90) + (at + 90 < full.length ? "\u2026" : "");
            results.push({ page: p, count, snippet });
          }
        }
        loading.hidden = true;
        if (inst.disposed) return;
        searchRes.innerHTML = "";
        if (!results.length) {
          searchRes.appendChild(el("div", "pv-search-none", "No matches for \u201c" + q + "\u201d"));
        } else {
          const total = results.reduce((a, r) => a + r.count, 0);
          searchRes.appendChild(el("div", "pv-search-head", results.length + " page" + (results.length === 1 ? "" : "s") + " \u00b7 " + total + " match" + (total === 1 ? "" : "es")));
          for (const r of results) {
            const row = el("button", "pv-search-row");
            row.type = "button";
            row.appendChild(el("span", "pv-search-pg", "p." + r.page));
            row.appendChild(el("span", "pv-search-snip", r.snippet));
            row.addEventListener("click", () => { goPage(r.page); });
            searchRes.appendChild(row);
          }
        }
        searchRes.hidden = false;
      })();
    }

