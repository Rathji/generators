  function ensureSamplePdfs() {
    try {
      const docs = window.FS && window.FS.resolve ? window.FS.resolve("/home/user/Documents") : null;
      if (!docs) return;
      for (const s of SAMPLES) {
        const content = buildPdf({ title: s.title, author: "Webuntu OS", pages: s.pages });
        const existing = docs.children.find((c) => c.name === s.name);
        if (existing) {
          if (existing.meta && existing.meta.content === content) continue;
          existing.meta.content = content;
          existing.meta.size = content.length;
          existing.meta.modified = Date.now();
          continue;
        }
        window.FS.create("/home/user/Documents", {
          type: "file", name: s.name, icon: "📕",
          meta: { content, size: content.length, modified: Date.now() },
        });
      }
    } catch (e) {
      console.warn("PDF sample seeding failed:", e);
    }
  }

  // ---------------- pdf.js engine (lazy, cached) ----------------------------
  let enginePromise = null;
  function ensureEngine() {
    if (!enginePromise) {
      enginePromise = (async () => {
        const mod = await import("https://esm.sh/pdfjs-dist@3.11.174");
        const pdfjs = mod.default;
        pdfjs.GlobalWorkerOptions.workerSrc = "https://cdn.jsdelivr.net/npm/pdfjs-dist@3.11.174/build/pdf.worker.min.js";
        return pdfjs;
      })();
      enginePromise.catch(() => { enginePromise = null; });
    }
    return enginePromise;
  }

