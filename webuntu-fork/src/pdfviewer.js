  function el(tag, cls, text) {
    const n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text !== undefined) n.textContent = text;
    return n;
  }
  function baseName(path) {
    const p = String(path || "").split("/").filter(Boolean);
    return p.length ? p[p.length - 1] : (path || "");
  }
  function fmt(n) {
    return String(Math.round(n * 100) / 100);
  }

  // ---------------- Latin-1 <-> bytes (the virtual FS stores PDFs as text) --
  function latin1ToBytes(str) {
    const s = String(str || "");
    const bytes = new Uint8Array(s.length);
    for (let i = 0; i < s.length; i++) bytes[i] = s.charCodeAt(i) & 0xFF;
    return bytes;
  }
  function isPdfString(content) {
    return typeof content === "string" && /^%PDF-/i.test(content.trim());
  }
  function isPdfNode(node) {
    return !!node && node.type === "file" && /\.pdf$/i.test(node.name || "") && isPdfString(node.meta && node.meta.content);
  }

  // ---------------- tiny PDF writer (seeded sample documents) ---------------
  // Helvetica width table (per 1000 units) for approximate line wrapping.
  const WIDTHS = {
    " ":278,"!":278,'"':355,"#":556,"$":556,"%":889,"&":667,"'":191,"(":333,")":333,"*":389,
    "+":584,",":278,"-":333,".":278,"/":278,"0":556,"1":556,"2":556,"3":556,"4":556,"5":556,
    "6":556,"7":556,"8":556,"9":556,":":278,";":278,"<":584,"=":584,">":584,"?":556,"@":1015,
    "A":667,"B":667,"C":722,"D":722,"E":667,"F":611,"G":778,"H":722,"I":278,"J":500,"K":667,
    "L":556,"M":833,"N":722,"O":778,"P":667,"Q":778,"R":722,"S":667,"T":611,"U":722,"V":667,
    "W":944,"X":667,"Y":667,"Z":611,"[":278,"\\":278,"]":278,"^":469,"_":556,"`":333,
    "a":556,"b":556,"c":500,"d":556,"e":556,"f":278,"g":556,"h":556,"i":222,"j":222,"k":500,
    "l":222,"m":833,"n":556,"o":556,"p":556,"q":556,"r":333,"s":500,"t":278,"u":556,"v":500,
    "w":722,"x":500,"y":500,"z":500,"{":334,"|":260,"}":334,"~":584,"\u00b7":278,
  };
  function textWidth(s, fs) {
    let w = 0;
    for (const ch of String(s)) w += (WIDTHS[ch] != null ? WIDTHS[ch] : 556);
    return (w * fs) / 1000;
  }
  function escPdfText(s) {
    return String(s)
      .replace(/[^\x20-\x7e\xa0-\xff]/g, "?")
      .replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
  }
  function wrapText(text, fs, maxW) {
    const words = String(text).split(/\s+/).filter(Boolean);
    const lines = [];
    let line = "";
    for (const w of words) {
      const test = line ? line + " " + w : w;
      if (!line || textWidth(test, fs) <= maxW) line = test;
      else { lines.push(line); line = w; }
    }
    if (line) lines.push(line);
    return lines;
  }
  function hexToOps(hex) {
    const m = /^#?([0-9a-f]{6})$/i.exec(String(hex || ""));
    if (!m) return "0.486 0.424 1";
    const n = parseInt(m[1], 16);
    return ((n >> 16) & 255) / 255 + " " + ((n >> 8) & 255) / 255 + " " + (n & 255) / 255;
  }

  const PDF_W = 612, PDF_H = 792, PDF_ML = 56, PDF_MR = 56, PDF_MT = 64, PDF_MB = 54, PDF_LW = PDF_W - PDF_ML - PDF_MR;
  const ACCENT = "#7c6cff", GRAY = "#7d8494";

  function blockHeight(b) {
    switch (b.t) {
      case "title": return 4 + 32 + 2;
      case "subtitle": return 19 + 2;
      case "h1": return 16 + 20 + 4;
      case "h2": return 10 + 17 + 2;
      case "p": return wrapText(b.text, 10.5, PDF_LW).length * 15.5 + 2;
      case "li": return wrapText(b.text, 10.5, PDF_LW - 18).length * 15.5 + 2;
      case "small": return wrapText(b.text, 8.5, PDF_LW).length * 12 + 2;
      case "rule": return 4 + 16;
      case "spacer": return b.h || 10;
    }
    return 10;
  }

  function blockOps(b, page) {
    const ops = page.ops;
    let y = page.y;
    const addText = (lines, font, fs, lh, colorOps, x) => {
      ops.push(colorOps + " rg");
      for (const ln of lines) {
        ops.push("BT " + font + " " + fs + " Tf 1 0 0 1 " + fmt(x) + " " + fmt(y) + " Tm (" + escPdfText(ln) + ") Tj ET");
        y -= lh;
      }
      page.y = y;
    };
    switch (b.t) {
      case "title": {
        y -= 6;
        addText(wrapText(b.text, 26, PDF_LW), "/F2", 26, 32, "0 0 0", PDF_ML);
        page.y = y - 2;
        break;
      }
      case "subtitle":
        addText([b.text], "/F1", 13, 19, hexToOps(b.color || ACCENT), PDF_ML);
        page.y = y - 4;
        break;
      case "h1":
        page.y = y - 16;
        addText(wrapText(b.text, 14.5, PDF_LW), "/F2", 14.5, 20, "0 0 0", PDF_ML);
        page.y = page.y - 4;
        break;
      case "h2":
        page.y = y - 10;
        addText(wrapText(b.text, 12, PDF_LW), "/F2", 12, 17, "0 0 0", PDF_ML);
        page.y = page.y - 2;
        break;
      case "p":
        addText(wrapText(b.text, 10.5, PDF_LW), "/F1", 10.5, 15.5, "0 0 0", PDF_ML);
        page.y = y - 2;
        break;
      case "li": {
        const wrapped = wrapText(b.text, 10.5, PDF_LW - 18);
        ops.push("0 0 0 rg");
        ops.push("BT /F1 10.5 Tf 1 0 0 1 " + fmt(PDF_ML) + " " + fmt(y) + " Tm (\u00b7) Tj ET");
        y -= 15.5;
        for (let i = 0; i < wrapped.length; i++) {
          ops.push("BT /F1 10.5 Tf 1 0 0 1 " + fmt(PDF_ML + 18) + " " + fmt(y) + " Tm (" + escPdfText(wrapped[i]) + ") Tj ET");
          y -= 15.5;
        }
        page.y = y - 2;
        break;
      }
      case "small":
        addText(wrapText(b.text, 8.5, PDF_LW), "/F1", 8.5, 12, hexToOps(b.color || GRAY), PDF_ML);
        page.y = y - 2;
        break;
      case "rule":
        ops.push(hexToOps(b.color || ACCENT) + " rg");
        ops.push(fmt(PDF_ML) + " " + fmt(y - 4) + " " + fmt(PDF_LW) + " 1.6 re f");
        page.y = y - 16;
        break;
      case "spacer":
        page.y = y - (b.h || 10);
        break;
    }
  }

  // doc: { title, author, pages: [ { blocks: [block...] } ] }
  function buildPdf(doc) {
    const rendered = [];      // { content } per page
    let cur = { y: PDF_H - PDF_MT, ops: [] };
    for (const pg of doc.pages || []) {
      if (cur.ops.length) { rendered.push(cur); cur = { y: PDF_H - PDF_MT, ops: [] }; }
      for (const b of pg.blocks || []) {
        if (b.t === "pagebreak") { if (cur.ops.length) rendered.push(cur); cur = { y: PDF_H - PDF_MT, ops: [] }; continue; }
        const h = blockHeight(b);
        if (cur.ops.length && cur.y - h < PDF_MB + 8) { rendered.push(cur); cur = { y: PDF_H - PDF_MT, ops: [] }; }
        blockOps(b, cur);
      }
    }
    if (cur.ops.length) rendered.push(cur);
    const N = rendered.length || 1;
    for (let i = 0; i < N; i++) {
      const footer = "Webuntu 12 \u00b7 Perch Mint";
      const num = "Page " + (i + 1) + " of " + N;
      const f = rendered[i].ops;
      f.push(hexToOps(GRAY) + " rg");
      f.push("BT /F1 8 Tf 1 0 0 1 " + fmt(PDF_ML) + " 30 Tm (" + escPdfText(footer) + ") Tj ET");
      f.push("BT /F1 8 Tf 1 0 0 1 " + fmt(PDF_W - PDF_MR - textWidth(num, 8)) + " 30 Tm (" + escPdfText(num) + ") Tj ET");
      rendered[i].content = f.join("\n") + "\n";
    }

    const chunks = [];
    let off = 0;
    const offsets = [0];
    function push(s) { chunks.push(s); off += s.length; }
    function obj(n, body) { offsets[n] = off; push(n + " 0 obj\n" + body + "\nendobj\n"); }

    push("%PDF-1.4\n%\u00e2\u00e3\u00cf\u00d3\n");
    obj(1, "<< /Type /Catalog /Pages 2 0 R >>");
    const kids = [];
    for (let i = 0; i < N; i++) kids.push((3 + i) + " 0 R");
    obj(2, "<< /Type /Pages /Kids [" + kids.join(" ") + "] /Count " + N + " >>");
    for (let i = 0; i < N; i++) {
      obj(3 + i, "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 " + PDF_W + " " + PDF_H + "] /Contents " + (3 + N + i) + " 0 R /Resources << /Font << /F1 " + (3 + 2 * N) + " 0 R /F2 " + (4 + 2 * N) + " 0 R >> >> >>");
    }
    for (let i = 0; i < N; i++) {
      const c = rendered[i].content;
      obj(3 + N + i, "<< /Length " + c.length + " >>\nstream\n" + c + "endstream");
    }
    const infoTitle = escPdfText((doc && doc.title) || "Webuntu document");
    const infoAuthor = escPdfText((doc && doc.author) || "Webuntu OS");
    obj(3 + 2 * N, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");
    obj(4 + 2 * N, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>");
    obj(5 + 2 * N, "<< /Title (" + infoTitle + ") /Author (" + infoAuthor + ") /Producer (Webuntu 12 PDF Writer) /CreationDate (D:20260828120000Z) >>");

    const xrefStart = off;
    const total = 6 + 2 * N;
    let xref = "xref\n0 " + total + "\n0000000000 65535 f \n";
    for (let i = 1; i < total; i++) xref += String(offsets[i]).padStart(10, "0") + " 00000 n \n";
    push(xref);
    push("trailer\n<< /Size " + total + " /Root 1 0 R /Info " + (5 + 2 * N) + " 0 R >>\nstartxref\n" + xrefStart + "\n%%EOF\n");
    return chunks.join("");
  }

