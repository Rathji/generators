// Webuntu OS — PDF Viewer (POST-52, Task 61)
// A real document viewer powered by pdf.js (3.11.174). It renders any valid
// PDF by opening it three ways:
//   • double-click a .pdf file in the File Manager (window.PDFViewer.openPath),
//   • the app's own Open dialog (scans the virtual FS for .pdf files),
//   • drag-and-drop a real PDF from the computer onto the window.
// The engine loads lazily on first use from esm.sh (main bundle) and a raw
// CDN classic script (worker) — the worker script runs as pdf.js's main-thread
// "fake worker", so no cross-origin Web Worker is needed. Features: thumbnail
// sidebar, page nav + jump, fit-width / fit-page / actual-size / zoom, search
// across pages, a selectable (invisible) text layer, status bar and graceful
// loading / error states.
// On first boot the module also seeds three sample PDFs into
// /home/user/Documents, generated by a tiny in-app PDF writer (uncompressed,
// ASCII-safe content streams + correct xref) so the viewer has something to
// open even with no network besides the two engine CDN files.

