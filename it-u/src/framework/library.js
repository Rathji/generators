// src/framework/library.js — the in-application LIBRARY of service processes
// and operational topics (roadmap task 35).
//
// Task 35 asks IT-U to provide a library of service processes and operational
// topics — articles that a technician or administrator can follow as written, or
// adapt to the provider's own context — and to cross-link each article from the
// assets and procedures it supports.
//
// This module is the CATALOG: pure data (the topics and the articles) plus the
// pure functions the rest of the app reads it with. An article declares which
// shipped asset templates it supports (`assetTypeIds`) and which document types
// it belongs to (`docTypes`), so the asset profile can offer "how to run this"
// guidance for a service, the document editor can offer "start from the
// library", and the Library station can browse and search it. The same article
// is adapted into a real document with `articleToDocumentInput`, which is what
// makes a library article usable *as written or adapted*, rather than a static
// help page.
//
// Nothing here is stored in a client's documentation set: the library is
// shared content, like the Flexible Asset template library. What a client's set
// holds is the DOCUMENT an article is adapted into (and the links from it).

