// ---- articles --------------------------------------------------------------
// `body` is markdown. `assetTypeIds` and `docTypes` are the CROSS-LINKS: they
// name the shipped asset templates this article supports and the document type
// it reads as, which is how the article is surfaced from an asset profile or a
// document editor.
function art({ id, title, topic, summary, tags = [], audience = "provider", assetTypeIds = [], docTypes = [], related = [], body }) {
  return {
    id,
    title,
    topic,
    summary,
    tags,
    audience,
    assetTypeIds,
    docTypes,
    related,
    body: (body || []).join("\n"),
  };
}

