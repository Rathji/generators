export const LIBRARY_ARTICLE_IDS = LIBRARY_ARTICLES.map((a) => a.id);
const ARTICLE_INDEX = new Map(LIBRARY_ARTICLES.map((a) => [a.id, a]));

export const libraryArticle = (id) => ARTICLE_INDEX.get(id) || null;
export const libraryArticleExists = (id) => ARTICLE_INDEX.has(id);

const asArray = (v) => (Array.isArray(v) ? v : v == null || v === "" ? [] : [v]);

// The articles matching a set of filters. Every filter is optional and they
// combine AND-wise; `query` matches the title, summary and tags
// case-insensitively.
export function libraryArticles({ topic, audience, assetTypeId, docType, query, ids } = {}) {
  const q = String(query || "").trim().toLowerCase();
  const wantedIds = ids ? new Set(asArray(ids)) : null;
  let list = LIBRARY_ARTICLES.slice();
  if (wantedIds) list = list.filter((a) => wantedIds.has(a.id));
  if (topic) list = list.filter((a) => a.topic === topic);
  if (audience) list = list.filter((a) => a.audience === audience);
  if (assetTypeId) list = list.filter((a) => a.assetTypeIds.includes(assetTypeId));
  if (docType) list = list.filter((a) => a.docTypes.includes(docType));
  if (q) {
    list = list.filter((a) => {
      const haystack = [a.title, a.summary, ...(a.tags || [])].join(" ").toLowerCase();
      return haystack.includes(q);
    });
  }
  return list;
}

// The articles that support a given shipped asset template — the cross-link the
// asset profile reads.
export const libraryForAssetType = (assetTypeId) => libraryArticles({ assetTypeId });

// The library equivalent of a document type — the cross-link the document
// editor reads.
export const libraryForDocType = (docType) => libraryArticles({ docType });

// Free-text search over the library.
export const searchLibrary = (query, opts = {}) => libraryArticles({ ...opts, query });

// Related articles for an article (its declared links, resolved), so the reader
// can walk the library horizontally rather than only by topic.
export function relatedLibraryArticles(article) {
  if (!article) return [];
  return (article.related || []).map((id) => libraryArticle(id)).filter(Boolean);
}

// The library's shape, for the station summary.
export function libraryStats() {
  const byTopic = {};
  for (const t of LIBRARY_TOPICS) byTopic[t.id] = libraryArticles({ topic: t.id }).length;
  return {
    articles: LIBRARY_ARTICLES.length,
    topics: LIBRARY_TOPICS.length,
    byTopic,
    assetTypeLinks: LIBRARY_ARTICLES.reduce((n, a) => n + a.assetTypeIds.length, 0),
    docTypeLinks: LIBRARY_ARTICLES.reduce((n, a) => n + a.docTypes.length, 0),
  };
}

// Which shipped asset templates the library actually has content for. The UI
// uses this to decide whether to offer "how to run this" on a template.
export function libraryAssetTypeIds() {
  const out = new Set();
  for (const a of LIBRARY_ARTICLES) for (const id of a.assetTypeIds) out.add(id);
  return [...out];
}

// The document type an article should become by default: its first declared
// docType that is a real document type, else a plain reference.
const REAL_DOC_TYPES = new Set(DOCUMENT_TYPES.map((d) => d.id));
export function articleDocumentType(article) {
  const list = (article && article.docTypes) || [];
  return list.find((d) => REAL_DOC_TYPES.has(d)) || "reference";
}

// Adapt an article into the input shape `docs.addDocument` accepts — this is the
// "usable as written or adapted" half of task 35. The body is the article's own
// markdown, so the created document can be edited freely without touching the
// library.
export function articleToDocumentInput(article, overrides = {}) {
  if (!article) return null;
  return {
    name: overrides.name || article.title,
    docType: overrides.docType || articleDocumentType(article),
    summary: overrides.summary || article.summary,
    body: overrides.body != null ? overrides.body : article.body,
    tags: overrides.tags || article.tags || [],
    informationModel: "document",
    provenance: "authored",
  };
}

// The header block an article is inserted into an existing document with, so an
// adapted article keeps a trail back to the library it came from.
export function articleInsertionText(article) {
  if (!article) return "";
  return [
    `## From the library: ${article.title}`,
    "",
    `> Adapted from the IT-U service library article “${article.title}” (${libraryTopicLabel(article.topic)}). Edit it freely for this client's context.`,
    "",
    article.body,
  ].join("\n");
}

