// src/framework/assetLibrary.js — the shipped Flexible Asset template library
// (roadmap tasks 12–13).
//
// These are the templates IT-U ships out of the box: Applications, Licensing
// and Virtualization (named by the roadmap) plus the service templates the
// later phases build on (email, backup, network, security, remote access, file
// sharing, printing, vendor, voice/PBX and internet/WAN circuit). They live in
// the ONE global library document (see ./flexibleTypes.js), so a house standard
// is defined once and shared across every client's documentation set; the
// provider can edit a builtin in place, clone it and adapt the clone, or reset
// it to the shipped definition.
//
// Field keys are EXPLICIT and stable so records, exports and tests can rely on
// them even as labels are tuned.

