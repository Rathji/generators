function tpl(id, name, category, icon, description, references, fields) {
  return {
    schema: ASSET_TYPE_SCHEMA,
    id,
    name,
    description,
    category,
    icon,
    fields: fields.map((f) => normalizeField(f)),
    references,
    builtin: true,
    customized: false,
    shipped: true,
    createdAt: 0,
    updatedAt: 0,
    createdBy: "system",
  };
}

